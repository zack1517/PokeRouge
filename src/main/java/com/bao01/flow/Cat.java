package com.bao01.flow;

/** 节点类别：决定进入节点后的处理方式与结算入口。 */
public enum Cat {

    /** 战斗节点：进入后先开战，按胜负结算（路人 / 野外 / 火箭队 / 神兽）。 */
    COMBAT,

    /** 服务节点：不战斗，直接执行服务逻辑（医院 / 商店）。 */
    SERVICE,

    /** 剧情事件节点：按剧情线状态执行（火箭队抓捕神兽）。 */
    STORY,

    /** 里程碑节点：必然触发、不消耗 AP（道馆 / 四天王 / 冠军 / 侵略）。 */
    MILESTONE
}
